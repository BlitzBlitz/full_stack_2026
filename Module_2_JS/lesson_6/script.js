//write a function that will take an array and a year,
// as input and return all the books published before this year

//in  array of books, year of publish
//cal  deklarojme nje array bosh
//    lexojm cdo element(liber)
//    per cdo liber kontrollojme daten e publikimit
//          nese data < year_of_publish
//            ruajme librin ne array-n bosh
//out books published before this year

function get_books_published_before(books_array, year_before) {
  let books_before_year = [];
  for (let index = 0; index < books_array.length; index++) {
    let current_book = books_array[index];
    if (current_book.published_year < year_before) {
      books_before_year.push(current_book);
    }
  }
  return books_before_year;
}

